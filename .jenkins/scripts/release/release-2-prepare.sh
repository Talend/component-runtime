set -xe

# Parameters:
# $1: release version
# $2: next version
# $3: tag name
# $4: extra build args for all mvn cmd
#
# Environment:
# DRY_RUN: when "true", release:prepare runs with -DdryRun=true. Poms are rewritten and validated
#          locally, but nothing is committed, tagged or pushed. Defaults to false.
main() {
  local releaseVersion="${1?Missing release version}"; shift
  local nextVersion="${1?Missing actual project version}"; shift
  local tagName="${1?Missing actual project version}"; shift
  local extraBuildParams=("$@")

  local dryRunParams=()
  if [[ "${DRY_RUN:-false}" == "true" ]]; then
    printf ">> DRY RUN: release:prepare will not commit, tag nor push\n"
    dryRunParams=(--define dryRun=true)
  fi

  printf ">> Maven prepare release %s (next-dev: %s; tag: %s)\n" "${releaseVersion}" "${nextVersion}" "${tagName}"

  # The documentation module generates tracked files (antora.yml, package-lock.json)
  # from the project version. Build and commit them now, otherwise the tag keeps stale values and
  # tags with the same antora version make the documentation site build fail (duplicate nav).
  # The phase is process-sources on purpose: it is enough for antora.yml. The generated_*.adoc files
  # need the compile and process-classes phases and are only regenerated by release-5. They are
  # not in the tag. Only the version links in generated_sample-index.adoc can be old on a
  # maintenance branch.
  printf ">> Regenerate documentation files before tagging\n"
  # The antora version is the SNAPSHOT version without suffix, which is the release version.
  mvn clean process-sources --batch-mode \
                    --projects documentation \
                    --define skipTests \
                    --define invoker.skip=true \
                    --define checkstyle.skip \
                    --define enforcer.skip=true \
                    --define rat.skip \
                    --settings .jenkins/settings.xml \
                    "${extraBuildParams[@]}"

  if ! grep -qE "^version: '${releaseVersion%%-*}'$" documentation/src/main/antora/antora.yml; then
    printf "WARN: antora.yml version is not %s\n" "${releaseVersion%%-*}" >&2
  fi
  git commit -a -m "[jenkins-release] update generated documentation for ${releaseVersion}" || true

  local release_profiles="release,gpg-keyring,gpg2"

  mvn release:prepare \
    --batch-mode \
    --errors \
    --define tag="${tagName}" \
    --define releaseVersion="${releaseVersion}" \
    --define developmentVersion="${nextVersion}" \
    --define arguments="-DskipTests -DskipITs -Dinvoker.skip=true -Dcheckstyle.skip -Denforcer.skip=true -Drat.skip" \
    --settings .jenkins/settings.xml \
    --activate-profiles "$release_profiles" \
    "${dryRunParams[@]}" \
    "${extraBuildParams[@]}"
}

main "$@"
